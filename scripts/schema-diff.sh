#!/bin/sh
# Compares the schema (tables, columns, keys, indexes) of two databases on the MariaDB server.
# Used to prove that a database built by migrations equals one built by sync() from the models.
#
# It must run INSIDE the database container, where the root password is available:
#   docker cp scripts/schema-diff.sh hh_secur_db_container:/tmp/schema-diff.sh
#   docker exec hh_secur_db_container sh /tmp/schema-diff.sh hh_secur_baseline hh_secur_migrated
#
# Prints "SCHEMAS IDENTICAL", or the differences (first 60 lines). Data is not compared. Foreign key
# names and their order are ignored (each server names them itself).
# See docs/migrations.md, section "Checking for schema drift".
set -e

if [ "$#" -ne 2 ]; then
  echo "Usage: schema-diff.sh <database A> <database B>" >&2
  exit 2
fi

A="$1"
B="$2"

# Foreign key names are generated by the server (the baseline does not name them), and the server
# numbers them in its own order. Compare the keys themselves: drop the names and sort the foreign key
# lines inside each table.
normalize() {
  sed -E 's/CONSTRAINT `[^`]+` FOREIGN KEY/FOREIGN KEY/' "$1" | awk '
    function flush(   i, j, t) {
      for (i = 1; i <= n; i++) for (j = i + 1; j <= n; j++) if (fk[j] < fk[i]) { t = fk[i]; fk[i] = fk[j]; fk[j] = t }
      for (i = 1; i <= n; i++) print fk[i] (i < n ? "," : "")
      n = 0
    }
    /^  FOREIGN KEY/ { line = $0; sub(/,$/, "", line); fk[++n] = line; next }
    { if (n > 0) flush(); print }
    END { if (n > 0) flush() }
  '
}

for d in "$A" "$B"; do
  mariadb-dump --compact --no-data -uroot -p"$MARIADB_ROOT_PASSWORD" "$d" > "/tmp/schema-raw-$d.sql"
  normalize "/tmp/schema-raw-$d.sql" > "/tmp/schema-$d.sql"
done

echo "lines: $(wc -l < "/tmp/schema-$A.sql") ($A) vs $(wc -l < "/tmp/schema-$B.sql") ($B)"

if diff "/tmp/schema-$A.sql" "/tmp/schema-$B.sql" > /tmp/schema.diff; then
  echo "SCHEMAS IDENTICAL"
else
  echo "DIFFERENCES (< is $A, > is $B):"
  head -60 /tmp/schema.diff
  exit 1
fi
